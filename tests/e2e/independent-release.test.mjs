import test from 'node:test';
import {unstable_splitSqlQuery} from 'wrangler';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {produceArtifact} from '../../scripts/build-delivery-artifact.mjs';
const require=createRequire(import.meta.url);
const wranglerRequire=createRequire(require.resolve('wrangler'));
const {Miniflare,convertV4MiniflareOptions}=wranglerRequire('miniflare');

// Provider responses exist only in this native-runtime test. No real mail is sent.
test('independent emitted artifact owns secure empty setup, native sessions and publication',async()=>{
 const temporary=await mkdtemp(join(tmpdir(),'lamp-independent-'));
 let runtime;
 try {
  const artifact=JSON.parse(await readFile(await produceArtifact({output:join(temporary,'artifact.json')}),'utf8'));
  const mail=[];
  const secret='test-bootstrap-secret-'.repeat(3);
  const bindings={...artifact.deploymentSpec.publicVariables,LAMP_APP_HOST:'app.lamp.test',LAMP_PAGE_HOST:'status.lamp.test',LAMP_BOOTSTRAP_SECRET:secret,MAIL_FROM_ADDRESS:'status@example.test',MAIL_PROVIDER_API_KEY:'test-only-provider',SUBSCRIBER_TOKEN_SECRET:'test-subscriber-secret-'.repeat(3),WEBHOOK_SIGNING_SECRET:'test-webhook-secret-'.repeat(3),RER_INSTALLATION_ID:'independent-local'};
  const modules=artifact.modules.map(module=>({type:module.type==='esm'?'ESModule':module.type==='compiled-wasm'?'CompiledWasm':'Text',path:module.name,contents:module.type==='compiled-wasm'?Buffer.from(module.contentBase64,'base64'):Buffer.from(module.contentBase64,'base64').toString()}));
  modules.sort((a,b)=>a.path===artifact.mainModule?-1:b.path===artifact.mainModule?1:0);
  const options=convertV4MiniflareOptions({port:12402,name:'lamp-independent',modules,compatibilityDate:artifact.deploymentSpec.compatibilityDate,compatibilityFlags:artifact.deploymentSpec.compatibilityFlags,bindings,d1Databases:{DB:'lamp-independent-db'},r2Buckets:{SNAPSHOTS:'lamp-independent-snapshots'},durableObjects:{SNAPSHOT_CACHE:{className:'SnapshotCache',useSQLite:true}},queueProducers:{JOBS:'lamp-independent-jobs'},resourcePersistencePath:join(temporary,'state'),serviceBindings:{ASSETS:async request=>{const asset=artifact.assets.find(asset=>asset.path===new URL(request.url).pathname);return asset?new Response(Buffer.from(asset.contentBase64,'base64'),{headers:{'Content-Type':asset.contentType}}):new Response(null,{status:404});}},outboundService:async request=>{assert.equal(new URL(request.url).hostname,'api.resend.com','unexpected external request');mail.push(await request.json());return Response.json({id:'test-only-mail-'+mail.length});}});
  runtime=new Miniflare(options);
  const db=await runtime.getD1Database('DB');
  for(const migration of artifact.deploymentSpec.migrations)await db.batch(unstable_splitSqlQuery(migration.sql).map(sql=>db.prepare(sql)));
  const request=(path,init={})=>runtime.dispatchFetch('https://app.lamp.test'+path,init);
  const publicRequest=(path,init={})=>runtime.dispatchFetch('https://status.lamp.test'+path,init);
  assert.equal((await request('/health')).status,200);
  assert.equal((await request('/setup/status')).status,409);
  assert.equal((await publicRequest('/')).status,503);
  assert.equal((await publicRequest('/setup/status')).status,404);
  assert.equal((await request('/api/app/session')).status,401);
  const owner={email:'owner@example.test',displayName:'Independent owner',pageName:'Independent Lamp',tagline:'Owner-run infrastructure status',timezone:'UTC'};
  const setup={method:'POST',headers:{Authorization:'Bearer '+secret,'Content-Type':'application/json'},body:JSON.stringify(owner)};
  assert.equal((await request('/setup',{...setup,headers:{Authorization:'Bearer wrong','Content-Type':'application/json'}})).status,401);
  assert.equal((await publicRequest('/setup',setup)).status,404);
  assert.equal((await request('/setup',{...setup,headers:{...setup.headers,Origin:'https://other.test'}})).status,403);
  assert.equal((await request('/setup',{...setup,body:JSON.stringify({...owner,timezone:'nonsense'})})).status,400);
  const created=await request('/setup',setup);
  assert.equal(created.status,201,await created.text());
  assert.equal(created.headers.get('set-cookie'),null);
  assert.equal((await request('/setup',setup)).status,409);
  assert.equal((await request('/setup/status')).status,200);
  assert.equal((await request('/health')).status,200);
  const publicPage=await publicRequest('/');
  assert.equal(publicPage.status,200);
  assert.equal(publicPage.headers.get('set-cookie'),null);
  assert.match(await publicPage.text(),/Independent Lamp/);
  assert.equal((await request('/signin')).status,200);
  assert.equal((await request('/signin/request',{method:'POST',body:new URLSearchParams({email:owner.email})})).status,202);
  assert.equal(mail.length,1);
  const link=mail[0].text.match(/https:\/\/[^\s]+/)[0];
  const signIn=await runtime.dispatchFetch(link,{redirect:'manual'});
  assert.equal(signIn.status,302);
  const cookie=signIn.headers.get('set-cookie').split(';')[0];
  assert.equal((await runtime.dispatchFetch(link,{redirect:'manual'})).status,400);
  assert.equal((await request('/api/app/session',{headers:{Cookie:cookie}})).status,200);
  const component=await request('/api/app/components',{method:'POST',headers:{Cookie:cookie,'Content-Type':'application/json'},body:JSON.stringify({name:'Owner API',description:'Persistent independent component',groupId:null,internal:false,displayOrder:0,note:''})});
  assert.equal(component.status,201,await component.text());
  assert.match(await (await publicRequest('/')).text(),/Owner API/);
  await runtime.dispose();runtime=undefined;
  runtime=new Miniflare(options);
  assert.equal((await request('/setup',setup)).status,409,'restart must never reopen bootstrap');
  assert.equal((await request('/api/app/session',{headers:{Cookie:cookie}})).status,200,'real persisted session survives restart');
  assert.match(await (await publicRequest('/')).text(),/Owner API/);
  assert.equal((await request('/api/app/session/signout',{method:'POST',headers:{Cookie:cookie}})).status,204);
  assert.equal((await request('/api/app/session',{headers:{Cookie:cookie}})).status,401);
 }finally{await runtime?.dispose();await rm(temporary,{recursive:true,force:true});}
});
